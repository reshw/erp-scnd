-- 서로 다른 날짜에 여러 전표로 정리되는 경우, 나중에 다시 추적하기 쉽게
-- 관련 전표번호와 역할을 자유형식 JSON으로 남겨둔다. FK/인덱스 없음 — 참고용.
-- 예: [{"journal_no": 246, "relation": "원 청구"}, {"journal_no": 258, "relation": "개인분 정산"}]
-- =============================================
ALTER TABLE journals
  ADD COLUMN IF NOT EXISTS related_journals jsonb;
